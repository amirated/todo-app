// Small inline SVG icons (no icon library needed). They inherit the text
// colour via `currentColor` and are hidden from screen readers: the button
// that contains them carries the accessible label.

function Icon({ children, size = 16 }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
    >
      {children}
    </svg>
  );
}

